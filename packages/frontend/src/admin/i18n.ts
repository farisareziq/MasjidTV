// Akses dalaman untuk fallback tersuai (contoh label 'noTenants' yang tiada
// dalam kedua-dua jadual — kekalkan gelagat baseline superuser).
export function i18nEntry(lang: string, key: string): string | undefined {
  return I18N[lang]?.[key];
}

export function t(key: string, vars: Record<string, string | number> = {}) {
  let s = (I18N[adminLang] && I18N[adminLang][key]) ?? (I18N.en[key] ?? key);
  for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

// renderAll disuntik oleh core.ts (mengelak import kitaran i18n <-> core).
let renderAllFn: () => void = () => {};
export function setRenderAll(fn: () => void): void { renderAllFn = fn; }

export function applyLang() {
  document.documentElement.lang = adminLang;
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t((el as HTMLElement).dataset.i18n!); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { (el as HTMLInputElement).placeholder = t((el as HTMLElement).dataset.i18nPlaceholder!); });
  const sel = $('adminLang');
  if (sel) sel.value = adminLang;
  renderAllFn();
}

export function setAdminLang(lang: string) {
  adminLang = lang === 'ms' ? 'ms' : 'en';
  localStorage.setItem(ADMIN_LANG_KEY, adminLang);
  applyLang();
}

// Baca bahasa semasa (digunakan modul ciri untuk fallback label tersuai).
export function currentAdminLang(): string {
  return adminLang;
}
